function stage(no, name, chapter, map, w, h, status, extra) {
  return { no, name, chapter, map, w, h, status, ...extra };
}

export function getCampaignStage(id) {
  return CAMPAIGN.stages[id] || null;
}

/** route=null 仅主线；route='blue'|'red' 仅该分歧线（不含主线） */
export function orderedStageIds(route = null) {
  const ids = [];
  for (const ch of CAMPAIGN.chapters) {
    if (route == null) {
      if (ch.route) continue;
    } else if (ch.route !== route) {
      continue;
    }
    ids.push(...ch.stages);
  }
  return ids;
}

export function choiceBeforeStage(stageId) {
  return CAMPAIGN.choices.find((c) => c.before === stageId) || null;
}
