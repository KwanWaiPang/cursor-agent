export function validateSprites(pal = PAL) {
  for (const [name, rows] of Object.entries(SPRITES)) {
    if (!rows.length) throw new Error(`${name} empty`);
    const w = rows[0].length;
    for (const row of rows) {
      if (row.length !== w) throw new Error(`${name} ragged ${row.length} != ${w}`);
      for (const ch of row) {
        if (!(ch in pal)) throw new Error(`${name} unknown pixel "${ch}"`);
      }
    }
  }
}
