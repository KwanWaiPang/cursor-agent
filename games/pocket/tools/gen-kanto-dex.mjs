/**
 * Regenerates src/gameplay/dex/kanto.ts from PokeAPI CSV dumps.
 *
 * Usage:
 *   mkdir -p /tmp/pokeapi && cd /tmp/pokeapi
 *   curl -sSL -O https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv
 *   curl -sSL -O https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon.csv
 *   curl -sSL -O https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_types.csv
 *   curl -sSL -O https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_stats.csv
 *   curl -sSL -O https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/types.csv
 *   curl -sSL -O https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv
 *   node games/pocket/tools/gen-kanto-dex.mjs /tmp/pokeapi
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2] || '/tmp/pokeapi';
const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/gameplay/dex');

function readCsv(f) {
  const lines = fs.readFileSync(path.join(dir, f), 'utf8').trim().split('\n');
  const headers = lines[0].split(',');
  return lines.slice(1).map((line) => {
    const cols = [];
    let cur = '';
    let q = false;
    for (const ch of line) {
      if (ch === '"') q = !q;
      else if (ch === ',' && !q) {
        cols.push(cur);
        cur = '';
      } else cur += ch;
    }
    cols.push(cur);
    const o = {};
    headers.forEach((h, i) => {
      o[h] = cols[i] ?? '';
    });
    return o;
  });
}

const names = readCsv('pokemon_species_names.csv');
const pokemon = readCsv('pokemon.csv');
const ptypes = readCsv('pokemon_types.csv');
const pstats = readCsv('pokemon_stats.csv');
const types = readCsv('types.csv');
const species = readCsv('pokemon_species.csv');

const typeById = Object.fromEntries(types.map((t) => [t.id, t.identifier]));
const STAT = { 1: 'hp', 2: 'atk', 3: 'def', 4: 'spa', 5: 'spd', 6: 'spe' };

const zh = {};
for (const row of names) {
  if (row.local_language_id !== '12') continue;
  const id = +row.pokemon_species_id;
  if (id < 1 || id > 151) continue;
  zh[id] = { name: row.name, genus: row.genus || '' };
}

const slug = {};
for (const row of species) {
  const id = +row.id;
  if (id < 1 || id > 151) continue;
  slug[id] = row.identifier;
}

const defaults = {};
for (const row of pokemon) {
  if (row.is_default !== '1') continue;
  const sid = +row.species_id;
  if (sid < 1 || sid > 151) continue;
  defaults[sid] = { pokemonId: +row.id, height: +row.height, weight: +row.weight };
}

const typeMap = {};
for (const row of ptypes) {
  const pid = +row.pokemon_id;
  if (pid < 1 || pid > 151) continue;
  (typeMap[pid] ||= []).push({ slot: +row.slot, type: typeById[row.type_id] });
}
for (const pid of Object.keys(typeMap)) typeMap[pid].sort((a, b) => a.slot - b.slot);

const statMap = {};
for (const row of pstats) {
  const pid = +row.pokemon_id;
  if (pid < 1 || pid > 151) continue;
  const key = STAT[row.stat_id];
  if (!key) continue;
  (statMap[pid] ||= {})[key] = +row.base_stat;
}

const entries = [];
const typeSet = new Set();
for (let id = 1; id <= 151; id++) {
  const d = defaults[id];
  if (!d || !zh[id] || !slug[id]) throw new Error(`missing ${id}`);
  const typesArr = (typeMap[d.pokemonId] || []).map((t) => t.type);
  const st = statMap[d.pokemonId];
  if (!st || !typesArr.length) throw new Error(`stats/types ${id}`);
  typesArr.forEach((t) => typeSet.add(t));
  entries.push({
    id,
    slug: slug[id],
    name: zh[id].name,
    genus: zh[id].genus,
    types: typesArr,
    base: { hp: st.hp, atk: st.atk, def: st.def, spa: st.spa, spd: st.spd, spe: st.spe },
    height: d.height,
    weight: d.weight,
  });
}

fs.mkdirSync(outDir, { recursive: true });
const body = `/**
 * Kanto Pokédex #001–151 — official names/types/stats from PokeAPI CSVs
 * (zh-Hans language_id=12). Generated by tools/gen-kanto-dex.mjs — do not edit by hand.
 */

export type DexTypeId =
${[...typeSet]
  .sort()
  .map((t) => `  | '${t}'`)
  .join('\n')};

export interface DexEntry {
  /** National dex number 1..151 */
  id: number;
  /** English slug, e.g. "bulbasaur" */
  slug: string;
  /** Simplified Chinese name */
  name: string;
  /** Chinese genus, e.g. "种子宝可梦" */
  genus: string;
  types: DexTypeId[];
  base: { hp: number; atk: number; def: number; spa: number; spd: number; spe: number };
  /** Decimetres */
  height: number;
  /** Hectograms */
  weight: number;
}

export const KANTO_DEX: readonly DexEntry[] = ${JSON.stringify(entries, null, 2)} as const;

export const KANTO_BY_SLUG: Record<string, DexEntry> = Object.fromEntries(
  KANTO_DEX.map((e) => [e.slug, e]),
);

export const KANTO_BY_ID: Record<number, DexEntry> = Object.fromEntries(
  KANTO_DEX.map((e) => [e.id, e]),
);
`;
fs.writeFileSync(path.join(outDir, 'kanto.ts'), body);
console.log(`wrote ${entries.length} entries -> ${path.join(outDir, 'kanto.ts')}`);
