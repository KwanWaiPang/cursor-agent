/** 绘制优先级：后绘者在上（中原压边陲） */
export const ZHOU_DRAW_ORDER = [
  "凉州",
  "南中",
  "交州",
  "幽州",
  "并州",
  "益州",
  "扬州",
  "荆南",
  "荆北",
  "青州",
  "冀州",
  "徐州",
  "淮南",
  "兖州",
  "豫州",
  "京兆",
  "司隶",
];

export function zhouOfLonLat(lon, lat) {
  // 由上到下优先中原细州
  const order = [...ZHOU_DRAW_ORDER].reverse();
  for (const z of order) {
    const ring = ZHOU_RINGS[z];
    if (ring && pointInRing(lon, lat, ring)) return z;
  }
  return null;
}

export function projectedZhouRegions() {
  return ZHOU_DRAW_ORDER.map((id) => ({
    id,
    ...ZHOU_STYLE[id],
    ring: projectRing(ZHOU_RINGS[id]),
    labelPos: labelCenter(ZHOU_RINGS[id]),
  }));
}

function labelCenter(ring) {
  let x = 0;
  let y = 0;
  const n = ring.length - 1;
  for (let i = 0; i < n; i++) {
    x += ring[i][0];
    y += ring[i][1];
  }
  return project(x / n, y / n);
}
